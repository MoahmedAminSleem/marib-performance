#!/bin/bash
# ============================================================
# R61 E2E — توحيد الفحوصات في مكتبة مشتركة (e2e_lib.sh)
# الجولة دي بتغيّر بنية الاختبار نفسها، ففحوصاتها الخاصة بتثبت
# إن المكتبة الجديدة بتعمل شغلها فعلًا:
#   0) البوابة الدايمة (tsc + الأعلام) — منقول للمكتبة
#   1) نفس الـ 17 مقارنة بالبايت ضد baselines مرفوعة على git
#      (نسخ من لقطات R59 المثبتة — الدليل على صفر تغيير سلوك)
#   2) canary: تلف مقصود لازم يتشاف — المقارنة مش شكلية
#   3) idempotence: مقارنة تانية على طول خضرا (ونظافة الـ UI مثبتة)
#      — مع إثبات إن الأوديت سجّل أثر الفحوصات الوظيفية (الفرع مقصود)
#   4) bootstrap: قاعدة من الصفر (ensureBoot) + 16 مقارنة خضرا
#      (audit مستثنى: أرشيف الجولات السابقة بيانات تاريخية مش
#      قابلة لإعادة التوليد من الكود)
#   5) عقد الواجهة + الوظيفية + UI smoke — زي كل جولة
# ============================================================
set -x
source "$(dirname "$0")/e2e_lib.sh"
cd "$E2E_ROOT"
mkdir -p "$E2E_SCRATCH"

# ---------- 0) البوابة الدايمة + البناء ----------
e2e_typecheck
e2e_build

# ---------- 1) القاعدة المزروعة (R56) + المقارنة ضد baselines المرفوعة ----------
e2e_seed_db r56
e2e_start_server
e2e_login_admin
e2e_compare_core
e2e_frontend_contract
e2e_functional_core
e2e_ui_smoke r61

# ---------- 2) canary: المقارنة لازم تمسك الفرق فعلًا ----------
echo '{"canary":true}' > "$E2E_SCRATCH/after/health.json"
e2e_cmp_json health; RC=$?
[ "$RC" -ne 0 ]; check "canary: تلف مقصود في health اتشاف (المقارنة مش شكلية)" $?

# ---------- 3) idempotence: نفس المقارنة تاني خضرا + الأوديت سجّل الأثر ----------
# audit مستثنى: الفحوصات الوظيفية نفسها بتكتب أوديت — اختلافه هو
# الدليل إنها شغالة. storage مستثنى: بيقيس الأحجام الفيزيائية لصفحات
# Postgres + قايمة top-N بالحجم — أي كتابة (حتى الملغاة بعدها) بتحرك
# الصفحات فبتغير الأرقام؛ ده تاريخ فيزيائي مش سلوك تطبيق (مقارنته
# الكاملة محفوظة في الخطوة 1 على القاعدة النضيفة).
e2e_compare_core audit storage
e2e_cmp_json audit; RC=$?
[ "$RC" -ne 0 ]; check "الأوديت سجّل أثر الفحوصات الوظيفية (الفرع عن الـ baseline مقصود)" $?

# ---------- 4) bootstrap: كل حاجة من checkout عاري من غير db_seeded ----------
e2e_stop_server
rm -rf "$E2E_SEED_BOOT" "$E2E_ROOT/.next/standalone/db"
e2e_bootstrap_seed
e2e_seed_db boot
e2e_start_server
e2e_login_admin
# storage مستثنى زي فوق (أحجام فيزيائية مختلفة من طبيعة القاعدة الجديدة)
# وaudit مستثنى (أرشيف الجولات السابقة بيانات تاريخية مش قابلة للتوليد)
e2e_compare_core audit storage
LINES=$(wc -l < "$E2E_ROOT/scripts/e2e_r61.sh")
[ "$LINES" -lt 90 ]; check "سكريبت الجولة بقى رفيع ($LINES سطر بدل 272)" $?

e2e_stop_server
e2e_summary
